const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const {
  filterTurnsForDate,
  normalizeVisibleTurns,
  highlightsFromTurns,
} = require('../src/daily-transcript');

// Local wall-clock time, so the 4 AM-to-4 AM workday holds in every time zone.
function localIso(year, month, day, hour, minute = 0, second = 0) {
  return new Date(year, month - 1, day, hour, minute, second).toISOString();
}

describe('daily visible-dialogue normalization', () => {
  it('keeps only target-date timestamped turns', () => {
    const turns = [
      { role: 'user', content: 'Earlier request', timestamp: localIso(2026, 7, 21, 10, 0) },
      { role: 'assistant', content: 'Earlier reply', timestamp: localIso(2026, 7, 21, 10, 1) },
      { role: 'user', content: 'Today request', timestamp: localIso(2026, 7, 22, 10, 0) },
      { role: 'assistant', content: 'Today reply', timestamp: localIso(2026, 7, 22, 10, 1) },
      { role: 'user', content: 'Unassignable request' },
    ];
    assert.deepEqual(filterTurnsForDate(turns, '2026-07-22').map(turn => turn.content), [
      'Today request',
      'Today reply',
    ]);
  });

  it('deduplicates duplicate records and joins consecutive visible replies', () => {
    const normalized = normalizeVisibleTurns([
      { role: 'user', content: 'Do the work' },
      { role: 'user', content: 'Do the work' },
      { role: 'assistant', content: 'I started.' },
      { role: 'assistant', content: 'I finished.' },
    ]);
    assert.deepEqual(normalized, [
      { role: 'user', content: 'Do the work' },
      { role: 'assistant', content: 'I started.\n\nI finished.' },
    ]);
  });

  it('drops injected Claude notices and preserves text after a slash-command wrapper', () => {
    const normalized = normalizeVisibleTurns([
      { role: 'user', content: '<task-notification><event>background status</event></task-notification>' },
      { role: 'user', content: 'Another Claude session sent a message: <teammate-message>worker output</teammate-message>' },
      { role: 'user', content: '<local-command-stdout>Set model to Opus</local-command-stdout>' },
      { role: 'user', content: '<bash-stderr>internal shell output</bash-stderr>' },
      { role: 'user', content: '<command-name>/clear</command-name> <command-message>clear</command-message> <command-args></command-args> run the delta for two days' },
      { role: 'assistant', content: 'I ran the delta.' },
    ]);
    assert.deepEqual(normalized.map(turn => turn.content), [
      'run the delta for two days',
      'I ran the delta.',
    ]);
  });

  it('removes injected notices that were previously merged into a real user turn', () => {
    const normalized = normalizeVisibleTurns([{
      role: 'user',
      content: 'Real request\n\n<task-notification><event>noise</event></task-notification>\n\nAnother Claude session sent a message: <teammate-message>worker noise</teammate-message> This came from another Claude session — not typed by your user, but generated by the harness.',
    }]);
    assert.deepEqual(normalized.map(turn => turn.content), ['Real request']);
  });

  it('preserves slash-command arguments when Claude changes wrapper order', () => {
    const normalized = normalizeVisibleTurns([{
      role: 'user',
      content: '<command-message>review</command-message><command-name>/review</command-name><command-args>Review ticket 123</command-args>',
    }]);
    assert.deepEqual(normalized.map(turn => turn.content), ['Review ticket 123']);
  });

  it('keeps custom slash commands but drops control commands', () => {
    const normalized = normalizeVisibleTurns([
      { role: 'user', content: '<command-message>clear</command-message><command-name>/clear</command-name><command-args></command-args>' },
      { role: 'user', content: '<command-message>pm-fact-refresh</command-message><command-name>/pm-fact-refresh</command-name>' },
      { role: 'assistant', content: 'Refresh succeeded.' },
    ]);
    assert.deepEqual(normalized.map(turn => turn.content), ['/pm-fact-refresh', 'Refresh succeeded.']);
  });

  it('builds highlights from dialogue without tools or file metadata', () => {
    const highlights = highlightsFromTurns([
      { role: 'user', content: 'Fix the totals' },
      { role: 'assistant', content: 'I fixed and verified them.' },
    ]);
    assert.equal(highlights.topic, 'Fix the totals');
    assert.deepEqual(highlights.userMessages, ['Fix the totals']);
    assert.deepEqual(highlights.toolCalls, []);
    assert.deepEqual(highlights.filePaths, []);
    assert.ok(highlights.lastExchanges.includes('assistant: I fixed and verified them.'));
  });
});
